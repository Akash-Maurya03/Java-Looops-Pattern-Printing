package Basics;

public class incredecrement {
    public static void main(String[] args) {
        int x = 10;
        System.out.println(x);
        x *= 5;
        System.out.println(x);
        x -= 5;
        System.out.println(x);
        x++;
        System.out.println(x);
        ++x;
        System.out.println(x);
    }
}
